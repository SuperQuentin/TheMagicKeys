"""Fill in the missing notes of a note/sample mapping CSV using the nearest available sample.

Usage:
    python generate_full_mapping.py <input_csv> <output_csv>

Example:
    python generate_full_mapping.py concert_harp_notes.csv concert_harp_notes_full.csv
"""

import argparse
import csv
import sys

from generate_partial_mapping import display_all_notes_mapping, note_sort_key, write_all_notes_mapping_csv


def read_partial_mapping(input_csv):
    """Read the (note, sample_note, file_path) rows produced by generate_partial_mapping.py."""
    partial_mapping = []
    with open(input_csv, newline="", encoding="utf-8") as csv_file:
        reader = csv.DictReader(csv_file)
        for row in reader:
            partial_mapping.append((row["note"], row["sample_note"], row["file_path"]))
    return partial_mapping


def build_full_mapping(partial_mapping):
    """Fill empty rows with the sample_note/file_path of the musically closest non-empty row."""
    non_empty_rows = [row for row in partial_mapping if row[1] and row[2]]

    full_mapping = []
    for note, sample_note, file_path in partial_mapping:
        if sample_note and file_path:
            full_mapping.append((note, sample_note, file_path))
            continue

        note_key = note_sort_key(note)
        closest_row = min(non_empty_rows, key=lambda row: abs(note_sort_key(row[0]) - note_key))
        full_mapping.append((note, closest_row[1], closest_row[2]))

    return full_mapping


def main():
    parser = argparse.ArgumentParser(description="Fill in missing notes using the closest available sample.")
    parser.add_argument("input_csv", help="CSV file (note, sample_note, file_path) generated by generate_partial_mapping.py.")
    parser.add_argument("output_csv", help="Path of the CSV output file to write.")
    args = parser.parse_args()

    partial_mapping = read_partial_mapping(args.input_csv)

    non_empty_count = sum(1 for row in partial_mapping if row[1] and row[2])
    if non_empty_count == 0:
        print(f"Error: no sample found in {args.input_csv}", file=sys.stderr)
        sys.exit(1)

    full_mapping = build_full_mapping(partial_mapping)

    display_all_notes_mapping(full_mapping)
    write_all_notes_mapping_csv(full_mapping, args.output_csv)


if __name__ == "__main__":
    main()
