"""Generate the wav files for all 85 piano notes from a full note/sample mapping CSV.

Usage:
    python generate_all_samples.py <input_csv> <output_dir>

Example:
    python generate_all_samples.py concert_harp_notes_full.csv output_concert_harp

For each row (note, sample_note, file_path):
- if note == sample_note, the file is copied as-is to output_dir.
- otherwise, the file is pitch-shifted from sample_note to note and saved to output_dir,
  with sample_note replaced by note in the output file name.
"""

import argparse
import csv
import os
import sys

import librosa
import numpy as np
import soundfile as sf

from generate_partial_mapping import note_sort_key


def trim_trailing_silence(data, sample_rate, threshold_db=-50, minimum_duration=0.5):
    """Remove a trailing run below threshold_db lasting at least minimum_duration."""
    threshold = 10 ** (threshold_db / 20)
    minimum_samples = int(sample_rate * minimum_duration)
    quiet_samples = np.abs(data) < threshold

    trailing_samples = 0
    for is_quiet in quiet_samples[::-1]:
        if not is_quiet:
            break
        trailing_samples += 1

    if trailing_samples < minimum_samples:
        return data

    return data[:max(1, len(data) - trailing_samples)]


def read_full_mapping(input_csv):
    """Read the (note, sample_note, file_path) rows produced by generate_full_mapping.py."""
    full_mapping = []
    with open(input_csv, newline="", encoding="utf-8") as csv_file:
        reader = csv.DictReader(csv_file)
        for row in reader:
            full_mapping.append((row["note"], row["sample_note"], row["file_path"]))
    return full_mapping


def build_output_file_name(file_name, sample_note, note, note_index):
    """Build the output file name with its zero-padded CSV row index."""
    base_name = os.path.basename(file_name)
    name, ext = os.path.splitext(base_name)
    parts = [note if part == sample_note else part for part in name.split("_")]
    return f"{note_index:03d}_" + "_".join(parts) + ext


def copy_sample(file_name, output_dir, note_index, threshold_db):
    """Write file_name as a mono WAV into output_dir."""
    output_file_name = f"{note_index:03d}_" + os.path.basename(file_name)
    output_path = os.path.join(output_dir, output_file_name)
    data, sample_rate = librosa.load(file_name, sr=None, mono=True)
    data = trim_trailing_silence(data, sample_rate, threshold_db=threshold_db)
    sf.write(output_path, data, sample_rate)
    return output_path


def pitch_shift_sample(file_name, sample_note, note, output_dir, note_index, threshold_db):
    """Pitch-shift file_name from sample_note to note and save it into output_dir."""
    n_steps = note_sort_key(note) - note_sort_key(sample_note)

    y, sr = librosa.load(file_name, sr=None, mono=True)
    # librosa's phase-vocoder shift does not preserve formants as well as rubberband --formant,
    # but it keeps shifts limited to a few semitones acceptable and needs no external binary.
    y_shifted = librosa.effects.pitch_shift(y, sr=sr, n_steps=n_steps)

    output_file_name = build_output_file_name(file_name, sample_note, note, note_index)
    output_path = os.path.join(output_dir, output_file_name)
    y_shifted = trim_trailing_silence(y_shifted, sr, threshold_db=threshold_db)
    sf.write(output_path, y_shifted, sr)
    return output_path, n_steps


def main():
    parser = argparse.ArgumentParser(description="Generate wav files for all piano notes from a full mapping CSV.")
    parser.add_argument("input_csv", help="CSV file (note, sample_note, file_name) generated by generate_full_mapping.py.")
    parser.add_argument("output_dir", help="Directory where the generated wav files are written.")
    parser.add_argument(
        "--threshold_db",
        type=float,
        default=-50,
        help="Trim trailing silence below this dB threshold (default: -50).",
    )
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)

    full_mapping = read_full_mapping(args.input_csv)
    total_size = 0

    for note_index, (note, sample_note, file_name) in enumerate(full_mapping, start=1):
        if not sample_note or not file_name:
            print(f"Warning: {note:<4} skipped, no sample available", file=sys.stderr)
            continue

        if note == sample_note:
            output_path = copy_sample(file_name, args.output_dir, note_index, args.threshold_db)
            total_size += os.path.getsize(output_path)
            print(f"{note:<4} copy          -> {output_path}")
        else:
            output_path, n_steps = pitch_shift_sample(
                file_name, sample_note, note, args.output_dir, note_index, args.threshold_db
            )
            total_size += os.path.getsize(output_path)
            print(f"{note:<4} shift {n_steps:+d} st  -> {output_path}")

    total_size_mb = total_size / (1024 ** 2)
    print(f"Total generated size: {total_size_mb:.2f} MB")
    if total_size_mb > 65:
        print("Warning: total generated size is greater than 65 MB", file=sys.stderr)


if __name__ == "__main__":
    main()
